function gatewayTool(
  id: string,
  name: string,
  description: string,
  schema?: Record<string, string>,
): CuratedToolDef {
  const inputSchema = schema
    ? registrySchemaToJsonSchema(schema)
    : registrySchemaToJsonSchema(GATEWAY_REGISTRY_SCHEMAS[id] ?? { input: 'string' });
  return {
    id,
    name,
    description,
    kind: 'gateway-mcp',
    gatewayToolId: id,
    inputSchema,
  };
}

function apiTool(
  id: string,
  name: string,
  description: string,
  inputSchema: Record<string, unknown>,
): CuratedToolDef {
  return { id, name, description, kind: 'api', inputSchema };
}

