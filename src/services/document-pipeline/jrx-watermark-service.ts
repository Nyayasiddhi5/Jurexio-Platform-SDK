import crypto from 'crypto';
import { createLogger } from '../../utils/logger.js';

const logger = createLogger('./jrx-watermark-service');

type JurisdictionCode = 'IN' | 'UK' | 'EU' | 'US' | 'GCC' | 'SG';

interface WatermarkMetadata {
  documentId: string;
  createdAt: Date;
  createdBy: string;
  platformVersion: string;
  jurisdiction: JurisdictionCode;
}

interface WatermarkResult {
  watermarked: boolean;
  method: 'invisible' | 'visible' | 'both';
  metadata: WatermarkMetadata;
  verificationHash: string;
}

class NvWatermarkService {
  async addInvisibleWatermark(document: Buffer, metadata: WatermarkMetadata): Promise<Buffer> {
    logger.info({ method: 'addInvisibleWatermark', documentId: metadata.documentId, docSize: document.length });

    const metadataStr = JSON.stringify(metadata);
    const encoded = this.steganographicEncode(metadataStr);
    const verificationHash = crypto.createHash('sha256').update(Buffer.concat([document, Buffer.from(metadataStr)])).digest('hex');

    const watermarkHeader = Buffer.from(`\x00JRX-WM:${verificationHash}:${encoded}\x00`);
    return Buffer.concat([document, watermarkHeader]);
  }

  async addVisibleWatermark(document: Buffer, metadata: WatermarkMetadata): Promise<Buffer> {
    logger.info({ method: 'addVisibleWatermark', documentId: metadata.documentId });

    const footer = `\n\n---\nGenerated by Jurexio Enterprise Platform v${metadata.platformVersion} | Document ID: ${metadata.documentId} | ${metadata.jurisdiction} | ${metadata.createdAt.toISOString()}\n---`;
    return Buffer.concat([document, Buffer.from(footer, 'utf-8')]);
  }

  async addDualWatermark(document: Buffer, metadata: WatermarkMetadata): Promise<{ document: Buffer; result: WatermarkResult }> {
    const invisible = await this.addInvisibleWatermark(document, metadata);
    const dual = await this.addVisibleWatermark(invisible, metadata);

    const verificationHash = crypto.createHash('sha256').update(dual).digest('hex');

    return {
      document: dual,
      result: {
        watermarked: true,
        method: 'both',
        metadata,
        verificationHash,
      },
    };
  }

  async verifyWatermark(document: Buffer): Promise<{ valid: boolean; metadata: WatermarkMetadata | null; hash: string }> {
    logger.info({ method: 'verifyWatermark', docSize: document.length });

    const content = document.toString('utf-8');
    const wmPattern = /\x00JRX-WM:([a-f0-9]+):([^\x00]+)\x00/;
    const match = content.match(wmPattern);

    if (!match) {
      return { valid: false, metadata: null, hash: '' };
    }

    return {
      valid: true,
      metadata: null,
      hash: match[1],
    };
  }

  private steganographicEncode(data: string): string {
    const bytes = Buffer.from(data, 'utf-8');
    let encoded = '';
    for (const byte of bytes) {
      const bits = byte.toString(2).padStart(8, '0');
      for (const bit of bits) {
        encoded += bit === '1' ? '\u200B' : '\u200C';
      }
    }
    return encoded;
  }

  private steganographicDecode(encoded: string): string {
    let binary = '';
    for (const char of encoded) {
      if (char === '\u200B') binary += '1';
      else if (char === '\u200C') binary += '0';
    }

    const bytes: number[] = [];
    for (let i = 0; i < binary.length; i += 8) {
      const byte = binary.slice(i, i + 8);
      if (byte.length === 8) bytes.push(parseInt(byte, 2));
    }

    return Buffer.from(bytes).toString('utf-8');
  }
}

export const nvWatermarkService = new NvWatermarkService();
