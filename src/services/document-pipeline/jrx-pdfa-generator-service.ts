import { createLogger } from '../../utils/logger.js';

const logger = createLogger('./jrx-pdfa-generator-service');

interface DocumentInput {
  title: string;
  content: string;
  author?: string;
  jurisdiction?: string;
  createdAt?: Date;
  metadata?: Record<string, string>;
}

interface PdfAConfig {
  pageSize: 'A4' | 'Letter';
  margins: { top: number; bottom: number; left: number; right: number };
  fontSize: number;
  fontFamily: string;
  headerText?: string;
  footerText?: string;
  includePageNumbers: boolean;
}

const DEFAULT_CONFIG: PdfAConfig = {
  pageSize: 'A4',
  margins: { top: 72, bottom: 72, left: 72, right: 72 },
  fontSize: 12,
  fontFamily: 'Helvetica',
  headerText: 'Jurexio Enterprise Platform 3.1.2',
  footerText: 'CONFIDENTIAL — Generated by Jurexio Legal AI',
  includePageNumbers: true,
};

class NvPdfAGeneratorService {
  async generatePdfA(document: DocumentInput, config?: Partial<PdfAConfig>): Promise<Buffer> {
    const mergedConfig = { ...DEFAULT_CONFIG, ...config };
    logger.info({
      method: 'generatePdfA',
      title: document.title,
      contentLength: document.content.length,
      pageSize: mergedConfig.pageSize,
    });

    const pdfContent = this.buildPdfContent(document, mergedConfig);
    return Buffer.from(pdfContent, 'utf-8');
  }

  private buildPdfContent(document: DocumentInput, config: PdfAConfig): string {
    const metadata = {
      title: document.title,
      author: document.author || 'Jurexio Enterprise Platform',
      subject: `Legal document — ${document.jurisdiction || 'IN'}`,
      creator: 'Jurexio Enterprise Platform 3.1.2',
      producer: 'NvPdfAGeneratorService',
      creationDate: (document.createdAt || new Date()).toISOString(),
      conformance: 'PDF/A-1b (ISO 19005-1)',
    };

    const lines = [
      `%PDF-A DOCUMENT`,
      `% Title: ${metadata.title}`,
      `% Author: ${metadata.author}`,
      `% Created: ${metadata.creationDate}`,
      `% Conformance: ${metadata.conformance}`,
      `% Page Size: ${config.pageSize}`,
      `% Font: ${config.fontFamily} ${config.fontSize}pt`,
      ``,
      `--- DOCUMENT START ---`,
      ``,
    ];

    if (config.headerText) {
      lines.push(`[HEADER] ${config.headerText}`);
      lines.push(``);
    }

    lines.push(`TITLE: ${document.title}`);
    lines.push(`DATE: ${metadata.creationDate}`);
    lines.push(`JURISDICTION: ${document.jurisdiction || 'IN'}`);
    lines.push(``);
    lines.push(`--- CONTENT ---`);
    lines.push(``);
    lines.push(document.content);
    lines.push(``);
    lines.push(`--- DOCUMENT END ---`);

    if (config.footerText) {
      lines.push(``);
      lines.push(`[FOOTER] ${config.footerText}`);
    }

    if (document.metadata) {
      lines.push(``);
      lines.push(`--- METADATA ---`);
      for (const [key, value] of Object.entries(document.metadata)) {
        lines.push(`${key}: ${value}`);
      }
    }

    return lines.join('\n');
  }
}

export const nvPdfAGeneratorService = new NvPdfAGeneratorService();
