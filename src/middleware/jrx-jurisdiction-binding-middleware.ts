/**
 * Attaches the full jurisdiction profile to req.jurisdictionProfile.
 * Must be applied BEFORE any AI call is made.
 * Default jurisdiction: IN (India).
 */
export function jurisdictionBindingMiddleware(
  req: Request,
  _res: Response,
  next: NextFunction
): void {
  const jurisdictionCode: string =
    (req.body?.jurisdiction as string) ||
    (req.query?.jurisdiction as string) ||
    (req.headers['x-jrx-jurisdiction'] as string) ||
    'IN';

  const profile = JURISDICTION_PROFILES[jurisdictionCode.toUpperCase()] || JURISDICTION_PROFILES['IN'];
  // @ts-expect-error NV-TS230 legacy typing gap (TS2322)
  req.jurisdictionProfile = profile;

  logger.debug('Jurisdiction bound', { code: profile.code, name: profile.name });
  next();
}

/**
 * Get a jurisdiction profile by code. Safe fallback to India.
 */
export function getJurisdictionProfile(code: string): JurisdictionProfile {
  return JURISDICTION_PROFILES[code?.toUpperCase()] || JURISDICTION_PROFILES['IN'];
}

/**
 * Build the jurisdiction system prompt injection.
 * Injected into EVERY AI system prompt to enforce jurisdiction awareness.
 */
export function buildJurisdictionSystemPromptClause(profile: JurisdictionProfile): string {
  return `
JURISDICTION BINDING (MANDATORY — DO NOT OVERRIDE):
- Jurisdiction: ${profile.name} (${profile.code})
- Currency: ${profile.currency} (${profile.currencySymbol}) — USE ONLY THIS CURRENCY. Do NOT use any other currency.
- Court System: ${profile.courtHierarchy.apex} (apex) → ${profile.courtHierarchy.trial[0]} (trial). Use ONLY courts from this jurisdiction.
- Criminal Law: ${profile.statutes.criminal} — reference ONLY this statute for criminal matters.
- Procedural Law: ${profile.statutes.procedural}
- Evidence Law: ${profile.statutes.evidence}
- Contract Law: ${profile.statutes.contract}
- Date Format: ${profile.dateFormat}
- Mandatory Disclosure: Always append — "${profile.mandatoryDisclosure}"
VIOLATION: Any output referencing another jurisdiction's currency, courts, or statutes will be flagged as high-risk.
`.trim();
}

/**
 * Build the governance badge for AI output screens.
 */
