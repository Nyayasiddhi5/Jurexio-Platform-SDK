export function validateProductionReadiness(): { ready: boolean; issues: string[] } {
  const issues: string[] = [];

  if (!process.env.DATABASE_URL) issues.push('DATABASE_URL not configured');
  if (!process.env.OPENROUTER_API_KEY) issues.push('OPENROUTER_API_KEY not configured — LLM calls will fail');
  if (!process.env.NYV_JWT_SECRET && !process.env.JWT_SECRET) issues.push('JWT_SECRET not configured');
  if (NYV_SDK_PRODUCTION.environment !== 'production') issues.push('NODE_ENV is not production');

  if (issues.length === 0) {
    logger.info('Production readiness check PASSED');
  } else {
    logger.warn('Production readiness issues found', { count: issues.length, issues });
  }

  return { ready: issues.length === 0, issues };
}

