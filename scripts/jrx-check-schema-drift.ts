const __dirname = dirname(__filename);

// ── Args / env ─────────────────────────────────────────────────────────────

const WARN_ONLY = process.argv.includes('--warn-only');
const DEFER_NV_SCHEMA_PARITY = process.env.JRX_DRIFT_STRICT_NV_SCHEMA !== '1';
const KEEP_PG = process.env.JRX_DRIFT_KEEP_PG === '1';
const VERBOSE = process.argv.includes('--verbose') || process.env.JRX_DRIFT_VERBOSE === '1';

const ROOT = resolve(__dirname, '..');
const DRIZZLE_DIR = join(ROOT, 'drizzle');
const MIGRATIONS_DIR = join(ROOT, 'migrations');

/**
 * R-SCHEMA-B backlog — column-level parity for these files is declared in TS
 * but the catch-up migrations have not landed, so their *forward* checks
 * (MISSING TABLE / MISSING COLUMN / TYPE MISMATCH / NOT NULL / DEFAULT) are
 * downgraded to warnings.
 *
 * NV-DRIFT-DEFER-SCAN-001 — these files are still PARSED. Skipping the parse
 * entirely (the behaviour before 2026-08-20) made the inverse checks
 * ("EXTRA DB TABLE … not declared in any TS schema export") report tables as
 * undeclared purely because the scan had chosen not to read the file where
 * they were declared: 9 of 18 violations were false positives on that path
 * (nv_digital_twins, agent_metrics, nv_agent_metrics, hallucination_checks,
 * ai_activity, nv_bipa_consent_records, nv_biometric_artefacts,
 * nv_rag_coverage_audit, memory_entries — all declared in
 * shared/jrx-governance-schema.ts). Deferral must narrow which *assertions*
 * run, never which declarations the scan can see.
 */
const DRIFT_DEFERRED_SCHEMA_FILES = new Set([
  'shared/jrx-governance-schema.ts',
]);

// Schema files are loaded directly from drizzle.config.ts so a new addition
// to the Drizzle config cannot silently bypass the drift check. See
// loadSchemaFilesFromDrizzleConfig() below.
async function loadSchemaFilesFromDrizzleConfig(): Promise<string[]> {
  const cfgPath = join(ROOT, 'drizzle.config.ts');
  if (!existsSync(cfgPath)) {
    throw new Error(`drizzle.config.ts not found at ${cfgPath}`);
  }
  const mod = (await import(cfgPath)) as { default?: { schema?: string | string[] } };
  const cfg = mod.default ?? (mod as unknown as { schema?: string | string[] });
  const raw = cfg?.schema;
  if (!raw) {
    throw new Error('drizzle.config.ts has no `schema` field — cannot determine which files to check');
  }
  const list = Array.isArray(raw) ? raw : [raw];
  // Normalise leading "./" so existsSync resolves cleanly.
  const normalised = list.map((p) => p.replace(/^\.\//, ''));
  for (const rel of normalised) {
    const abs = join(ROOT, rel);
    if (!existsSync(abs)) {
      throw new Error(`drizzle.config.ts references missing schema file: ${rel}`);
    }
  }
  // Every configured file is returned — deferral is applied per-assertion in
  // compare(), not by hiding the file from the scan (NV-DRIFT-DEFER-SCAN-001).
  return normalised;
}

// ── Postgres lifecycle ─────────────────────────────────────────────────────

function findFreePort(): Promise<number> {
  return new Promise((resolveP, rejectP) => {
    const srv = createServer();
    srv.unref();
    srv.on('error', rejectP);
    srv.listen(0, () => {
      const addr = srv.address();
      if (typeof addr === 'object' && addr) {
        const port = addr.port;
        srv.close(() => resolveP(port));
      } else {
        rejectP(new Error('could not bind ephemeral port'));
      }
    });
  });
}

interface PgHandle {
  port: number;
  dataDir: string;
  socketDir: string;
  child: ChildProcess | null;
  connectionString: string;
}

function run(cmd: string, args: string[], opts: { allowFail?: boolean; env?: NodeJS.ProcessEnv } = {}): { code: number; stdout: string; stderr: string } {
  const r = spawnSync(cmd, args, { encoding: 'utf8', env: { ...process.env, ...(opts.env ?? {}) } });
  if (!opts.allowFail && r.status !== 0) {
    console.error(`[drift] ✗ ${cmd} ${args.join(' ')} exited ${r.status}`);
    if (r.stdout) console.error(r.stdout);
    if (r.stderr) console.error(r.stderr);
    throw new Error(`${cmd} failed`);
  }
  return { code: r.status ?? 0, stdout: r.stdout ?? '', stderr: r.stderr ?? '' };
}

async function startPostgres(): Promise<PgHandle> {
  const port = await findFreePort();
  const dataDir = mkdtempSync(join(tmpdir(), './jrx-drift-pg-'));
  const socketDir = mkdtempSync(join(tmpdir(), './jrx-drift-sock-'));

  console.log(`[drift] initdb in ${dataDir} (port ${port}) …`);
  // macOS/Homebrew often lacks the host locale Postgres expects — force C.UTF-8.
  const pgEnv = { ...process.env, LC_ALL: 'C', LANG: 'C' };
  run('initdb', ['-D', dataDir, '-U', 'postgres', '-A', 'trust', '--encoding=UTF8', '--locale=C', '--no-instructions'], { env: pgEnv });

  const logFile = join(dataDir, 'postgres.log');
  // -F: no fsync (faster, throwaway DB). -k: socket dir. -h '': no TCP listen
  // would be ideal, but we still bind to localhost for psql -h compatibility.
  const pgOpts = `-p ${port} -k ${socketDir} -F`;
  console.log(`[drift] starting postgres (log: ${logFile}) …`);
  run('pg_ctl', ['-D', dataDir, '-l', logFile, '-o', pgOpts, '-w', 'start'], { env: pgEnv });

  // Create the working DB.
  run('psql', ['-h', socketDir, '-p', String(port), '-U', 'postgres', '-d', 'postgres', '-c', 'CREATE DATABASE drift_check'], { env: pgEnv });

  const connectionString = `postgresql://postgres@localhost:${port}/drift_check?host=${socketDir}`;
  return { port, dataDir, socketDir, child: null, connectionString };
}

function stopPostgres(h: PgHandle): void {
  if (KEEP_PG) {
    console.log(`[drift] JRX_DRIFT_KEEP_PG=1 — leaving Postgres running:`);
    console.log(`        socket: ${h.socketDir}`);
    console.log(`        port:   ${h.port}`);
    console.log(`        data:   ${h.dataDir}`);
    console.log(`        psql -h ${h.socketDir} -p ${h.port} -U postgres -d drift_check`);
    return;
  }
  const pgEnv = { ...process.env, LC_ALL: 'C', LANG: 'C' };
  try {
    run('pg_ctl', ['-D', h.dataDir, '-m', 'immediate', '-w', 'stop'], { allowFail: true, env: pgEnv });
  } catch {
    // best-effort
  }
  try { rmSync(h.dataDir, { recursive: true, force: true }); } catch { /* ignore */ }
  try { rmSync(h.socketDir, { recursive: true, force: true }); } catch { /* ignore */ }
}

// ── Migration application ──────────────────────────────────────────────────

function listMigrations(): { path: string; label: string }[] {
  const out: { path: string; label: string }[] = [];

  // 1. Drizzle auto-generated migrations
  if (existsSync(DRIZZLE_DIR)) {
    const files = readdirSync(DRIZZLE_DIR)
      .filter((f) => f.endsWith('.sql'))
      .sort();
    for (const f of files) out.push({ path: join(DRIZZLE_DIR, f), label: `drizzle/${f}` });
  }

  // 2. Hand-written catch-up migrations
  if (existsSync(MIGRATIONS_DIR)) {
    const files = readdirSync(MIGRATIONS_DIR)
      .filter((f) => f.endsWith('.sql'))
      .sort();
    for (const f of files) out.push({ path: join(MIGRATIONS_DIR, f), label: `migrations/${f}` });
  }

  return out;
}

interface MigrationApplyResult {
  appliedAll: boolean;
  failedAt: string | null;
  failureSummary: string | null;
}

function applyMigrations(h: PgHandle): MigrationApplyResult {
  const migrations = listMigrations();
  const pgEnv = { ...process.env, LC_ALL: 'C', LANG: 'C' };
  console.log(`[drift] applying ${migrations.length} migration files…`);

  for (const m of migrations) {
    if (VERBOSE) console.log(`[drift]   - ${m.label}`);
    const psqlArgs = [
      '-h', h.socketDir,
      '-p', String(h.port),
      '-U', 'postgres',
      '-d', 'drift_check',
      '-v', 'ON_ERROR_STOP=1',
      '-f', m.path,
    ];
    const r = spawnSync('psql', psqlArgs, { encoding: 'utf8', env: pgEnv });
    if (r.status !== 0) {
      const errOut = (r.stderr || '').trim() || (r.stdout || '').trim();
      // Show the actual SQL error so the operator can fix the migration.
      const firstError = errOut.split('\n').find((l) => l.toLowerCase().includes('error')) ?? errOut.split('\n')[0] ?? '';
      console.error(`[drift] ✗ migration failed: ${m.label}`);
      console.error(errOut);
      return { appliedAll: false, failedAt: m.label, failureSummary: firstError.trim() };
    }
  }
  console.log(`[drift] ✓ all migrations applied cleanly`);
  return { appliedAll: true, failedAt: null, failureSummary: null };
}

// ── Drizzle reflection ─────────────────────────────────────────────────────

interface DrizzleColumnSpec {
  name: string;
  drizzleType: string;
  notNull: boolean;
  hasDefault: boolean;
}

interface DrizzleTableSpec {
  exportName: string;
  schema: string;
  name: string;
  columns: DrizzleColumnSpec[];
  /** True when the declaring file is on the R-SCHEMA-B deferral list. */
  deferred: boolean;
}

function collectDrizzleTables(mod: Record<string, unknown>, sourceFile: string): DrizzleTableSpec[] {
  const out: DrizzleTableSpec[] = [];
  const deferred = DRIFT_DEFERRED_SCHEMA_FILES.has(sourceFile);
  for (const [exportName, value] of Object.entries(mod)) {
    if (!value || typeof value !== 'object') continue;
    let cfg: ReturnType<typeof getTableConfig> | null = null;
    try {
      cfg = getTableConfig(value as never);
    } catch {
      continue;
    }
    if (!cfg?.name) continue;
    const cols: DrizzleColumnSpec[] = (cfg.columns ?? []).map((c) => ({
      name: c.name,
      drizzleType: c.constructor?.name ?? 'unknown',
      notNull: !!c.notNull,
      hasDefault: !!c.hasDefault || c.default !== undefined,
    }));
    out.push({
      exportName: `${sourceFile}::${exportName}`,
      schema: cfg.schema ?? 'public',
      name: cfg.name,
      columns: cols,
      deferred,
    });
  }
  return out;
}

async function loadAllDrizzleTables(schemaFiles: string[]): Promise<DrizzleTableSpec[]> {
  const tables: DrizzleTableSpec[] = [];
  for (const rel of schemaFiles) {
    const abs = join(ROOT, rel);
    // Use a TS loader on import. tsx is the project-standard runner; when this
    // script is itself launched by `npx tsx` (see the bash wrapper) dynamic
    // imports of .ts files just work.
    const mod = (await import(abs)) as Record<string, unknown>;
    tables.push(...collectDrizzleTables(mod, rel));
  }
  return tables;
}

// ── Type compatibility (mirrors jrx-schema-parity-check.ts) ─────────────────

const TYPE_COMPAT: Record<string, RegExp> = {
  PgText: /^text$/,
  PgVarchar: /^(character varying|text)$/,
  PgChar: /^character$/,
  PgInteger: /^(integer|bigint|smallint)$/,
  PgBigInt53: /^(bigint|integer)$/,
  PgSmallInt: /^smallint$/,
  PgSerial: /^integer$/,
  PgBigSerial53: /^bigint$/,
  PgSmallSerial: /^smallint$/,
  PgBoolean: /^boolean$/,
  PgTimestamp: /^timestamp/,
  PgTimestampTz: /^timestamp/,
  PgDate: /^date$/,
  PgTime: /^time/,
  PgUUID: /^uuid$/,
  PgJsonb: /^jsonb$/,
  PgJson: /^json$/,
  PgNumeric: /^numeric$/,
  PgReal: /^real$/,
  PgDoublePrecision: /^double precision$/,
  PgArray: /^ARRAY$/,
  PgVector: /^USER-DEFINED$/,
  PgEnumColumn: /^USER-DEFINED$/,
  PgCustomColumn: /.*/,
};

function typesCompatible(drizzleType: string, dbType: string): boolean {
  const re = TYPE_COMPAT[drizzleType];
  if (!re) return true; // unknown drizzle type → don't fail
  return re.test(dbType);
}

// ── Main comparison ───────────────────────────────────────────────────────

interface DbColumn {
  column_name: string;
  data_type: string;
  is_nullable: 'YES' | 'NO';
  column_default: string | null;
}

async function compare(h: PgHandle, drizzleTables: DrizzleTableSpec[]): Promise<{ violations: string[]; warnings: string[] }> {
  const pool = new pg.Pool({ connectionString: h.connectionString, max: 2 });

  const violations: string[] = [];
  const warnings: string[] = [];

  // Group Drizzle tables by qualified name so we can detect duplicate exports.
  const byQname = new Map<string, DrizzleTableSpec[]>();
  for (const t of drizzleTables) {
    const k = `${t.schema}.${t.name}`;
    const arr = byQname.get(k) ?? [];
    arr.push(t);
    byQname.set(k, arr);
  }

  for (const [qname, group] of byQname) {
    // Multiple exports for the same table is fine when they all declare the
    // same shape (some tables are re-exported from jrx-schema-tables.ts and
    // jrx-governance-schema.ts). We compare each one independently against the
    // DB and dedupe the resulting messages.
    const [schemaName, tableName] = qname.split('.');
    // A table whose every declaration comes from an R-SCHEMA-B-deferred file
    // has its *forward* assertions downgraded to warnings. The declarations
    // themselves are always visible to the inverse scans below
    // (NV-DRIFT-DEFER-SCAN-001).
    const groupDeferred = group.every((g) => g.deferred);
    const r = await pool.query<DbColumn>(
      `SELECT column_name, data_type, is_nullable, column_default
         FROM information_schema.columns
         WHERE table_schema = $1 AND table_name = $2`,
      [schemaName, tableName],
    );
    const dbCols = r.rows;

    if (dbCols.length === 0) {
      if (groupDeferred || (DEFER_NV_SCHEMA_PARITY && schemaName === 'nv_schema')) {
        warnings.push(`DEFERRED (R-SCHEMA-B): ${qname} — nv_schema catch-up migration pending`);
        continue;
      }
      violations.push(`MISSING TABLE: ${qname} (declared in ${group.map((g) => g.exportName).join(', ')})`);
      continue;
    }

    const dbColMap = new Map(dbCols.map((c) => [c.column_name, c]));
    const declaredColNames = new Set<string>();
    const reported = new Set<string>(); // dedupe across duplicate exports

    for (const t of group) {
      // Forward assertions for a deferred declaration are warnings, not
      // violations — the R-SCHEMA-B catch-up migrations have not landed yet.
      const sink = t.deferred ? warnings : violations;
      const prefix = t.deferred ? 'DEFERRED (R-SCHEMA-B) ' : '';
      for (const dCol of t.columns) {
        declaredColNames.add(dCol.name);
        const db = dbColMap.get(dCol.name);
        if (!db) {
          const msg = `${prefix}MISSING COLUMN: ${qname}.${dCol.name} (Drizzle ${dCol.drizzleType}; declared in ${t.exportName}) — migrations need a CREATE/ALTER for this column`;
          if (!reported.has(msg)) { sink.push(msg); reported.add(msg); }
          continue;
        }
        if (!typesCompatible(dCol.drizzleType, db.data_type)) {
          const msg = `${prefix}TYPE MISMATCH: ${qname}.${dCol.name} — Drizzle ${dCol.drizzleType} vs DB ${db.data_type} (declared in ${t.exportName})`;
          if (!reported.has(msg)) { sink.push(msg); reported.add(msg); }
        }
        // NOT NULL parity (both directions).
        const dbNotNull = db.is_nullable === 'NO';
        if (dCol.notNull && !dbNotNull) {
          const msg = `${prefix}NOT NULL MISMATCH: ${qname}.${dCol.name} — Drizzle declares NOT NULL but DB is nullable (declared in ${t.exportName})`;
          if (!reported.has(msg)) { sink.push(msg); reported.add(msg); }
        }
        if (!dCol.notNull && dbNotNull) {
          // DB is stricter than TS — Drizzle inserts that omit the column
          // (because TS thinks it's optional) will fail at runtime. Treated
          // as a violation per the bidirectional contract in task #269.
          const msg = `${prefix}NOT NULL MISMATCH (db stricter): ${qname}.${dCol.name} — DB is NOT NULL but Drizzle is nullable (declared in ${t.exportName})`;
          if (!reported.has(msg)) { sink.push(msg); reported.add(msg); }
        }
        // Default-presence parity. We don't compare the actual default
        // expression because Drizzle stores it as raw SQL while Postgres
        // stores it post-parse, and false positives would dominate. But
        // presence-vs-absence is a real signal: TS callers that rely on
        // Drizzle's default (and therefore omit the column on INSERT) will
        // either get a NOT NULL failure (when the column is NOT NULL) or a
        // NULL stored where they expected the default value (when it's
        // nullable). Both are real bugs — task #263 was the NOT NULL flavour
        // for sdk_workflows.steps / triggers / status — so we treat both as
        // violations rather than warnings.
        if (dCol.hasDefault && db.column_default == null) {
          const msg = `${prefix}DEFAULT MISSING: ${qname}.${dCol.name} — Drizzle declares a default but DB has none (declared in ${t.exportName})`;
          if (!reported.has(msg)) { sink.push(msg); reported.add(msg); }
        }
        if (!dCol.hasDefault && db.column_default != null) {
          // Inverse: DB has a default the TS schema doesn't know about. Less
          // severe (TS writes still succeed) but still divergence.
          const msg = `${prefix}DEFAULT EXTRA: ${qname}.${dCol.name} — DB has default \`${db.column_default}\` but Drizzle declares none (declared in ${t.exportName})`;
          if (!reported.has(msg)) { sink.push(msg); reported.add(msg); }
        }
      }
    }

    // Migrations ahead of TS (extra DB columns). Per task #269 the check
    // must fail bidirectionally, so this is a violation: a column that
    // exists in the DB but not in any TS schema export means the type system
    // can't see it, runtime SELECT *-style code can return fields the
    // application doesn't model, and future drizzle-kit pushes may try to
    // drop it. Either declare it in TS or remove it from the migrations.
    for (const dbCol of dbCols) {
      if (!declaredColNames.has(dbCol.column_name)) {
        if (dbCol.column_name.endsWith('_enc')) {
          warnings.push(`DEFERRED encrypted column: ${qname}.${dbCol.column_name}`);
          continue;
        }
        const msg = `EXTRA DB COLUMN: ${qname}.${dbCol.column_name} (${dbCol.data_type}) created by migrations but not declared in any TS schema export`;
        if (groupDeferred) warnings.push(`DEFERRED (R-SCHEMA-B) ${msg}`);
        else violations.push(msg);
      }
    }
  }

  // Tables that exist in the DB after migrations but are not declared in any
  // TS schema export — also bidirectional drift.
  const declaredQnames = new Set(byQname.keys());
  const allDbTables = await pool.query<{ table_schema: string; table_name: string }>(
    `SELECT table_schema, table_name
       FROM information_schema.tables
       WHERE table_type = 'BASE TABLE'
         AND table_schema NOT IN ('pg_catalog', 'information_schema')`,
  );
  // Allow the migration-bookkeeping tables and a few well-known infrastructure
  // tables to stay undeclared — they are never read by application code and
  // exist purely to support migrations / extensions.
  const ALLOWED_UNDECLARED = new Set<string>([
    'public.__drizzle_migrations',
    'public.drizzle_migrations',
    'public.sdk_key_legacy_id_map',
    'public.nyv_sdk_legacy_id_map', // JRX-NS-002 backfill map (0006)
    'public.nv_rls_sentinel',
    'public.nv_rls_sentinel_v2',
    'public.nv_runtime_flag_overrides', // 0007
    'public.nv_model_catalog', // seeded by migrations/nv_model_catalog_2026-05-09.sql
    'public.nv_llm_providers', // created+seeded by migrations/2026-06-25-jrx-llm-providers-courts.sql (raw-SQL master data, not Drizzle-managed)
    'public.nv_courts', // created+seeded by migrations/2026-06-25-jrx-llm-providers-courts.sql (raw-SQL master data, not Drizzle-managed)
    'public.nv_statutes', // runtime-seeded by jrx-statute-seeding-service + migrations/2026-06-25-statutes-expansion.sql (raw-SQL/FTS table, not Drizzle-managed)
    'public.rag_documents', // created by migrations/2026-06-26-rag-documents.sql (pgvector secondary RAG store, raw-SQL, not Drizzle-managed)
  ]);
  for (const row of allDbTables.rows) {
    const k = `${row.table_schema}.${row.table_name}`;
    if (declaredQnames.has(k)) continue;
    if (ALLOWED_UNDECLARED.has(k)) continue;
    if (k.startsWith('pg_') || k.endsWith('_drizzle_internal')) continue;
    violations.push(`EXTRA DB TABLE: ${k} created by migrations but not declared in any TS schema export — declare it in shared/** or move it to ALLOWED_UNDECLARED with justification`);
  }

  await pool.end();
  return { violations, warnings };
}

// ── Entrypoint ────────────────────────────────────────────────────────────

async function main() {
  let pgHandle: PgHandle | null = null;
  let exitCode = 0;
  try {
    console.log('═'.repeat(70));
    console.log(' NV-SCHEMA-DRIFT-001 — TS schema ⇄ checked-in migrations');
    console.log('═'.repeat(70));

    pgHandle = await startPostgres();
    const apply = applyMigrations(pgHandle);

    let violations: string[] = [];
    let warnings: string[] = [];

    if (!apply.appliedAll) {
      // A migration that fails to apply on a fresh DB is itself drift — it
      // means the checked-in migration set assumes a column/table that no
      // earlier migration creates (the exact failure mode this guardrail is
      // designed to catch). Surface it as a top-level violation rather than
      // swallowing it as an "infrastructure" error.
      violations.push(
        `MIGRATION FAILS ON FRESH DB: ${apply.failedAt} — ${apply.failureSummary ?? 'see psql output above'}. ` +
        `The migration set is not self-contained: a fresh \`createdb\` + \`psql -f\` of the checked-in files cannot reach the schema declared in shared/**. ` +
        `Fix by adding the missing CREATE/ALTER to an earlier migration (or a hand-written file under Jurexio-Platform-SDK/migrations/) so this file applies cleanly.`,
      );
    } else {
      console.log('[drift] loading schema file list from drizzle.config.ts…');
      const schemaFiles = await loadSchemaFilesFromDrizzleConfig();
      if (DRIFT_DEFERRED_SCHEMA_FILES.size) {
        console.log(`[drift]   R-SCHEMA-B files (parsed; forward assertions downgraded to warnings): ${[...DRIFT_DEFERRED_SCHEMA_FILES].join(', ')}`);
      }
      console.log(`[drift]   ${schemaFiles.length} schema files: ${schemaFiles.join(', ')}`);

      console.log('[drift] reflecting Drizzle schema exports…');
      const drizzleTables = await loadAllDrizzleTables(schemaFiles);
      const deferredCount = drizzleTables.filter((t) => t.deferred).length;
      console.log(`[drift]   ${drizzleTables.length} table exports across ${schemaFiles.length} schema files (${deferredCount} from deferred files)`);

      console.log('[drift] comparing TS schema vs migrated DB…');
      const cmp = await compare(pgHandle, drizzleTables);
      violations = cmp.violations;
      warnings = cmp.warnings;
    }

    console.log('');
    console.log('─'.repeat(70));
    console.log(` ✗ Violations: ${violations.length}`);
    console.log(` ⚠ Warnings:   ${warnings.length}`);
    console.log('─'.repeat(70));

    if (violations.length) {
      console.log('\nVIOLATIONS (TS schema is ahead of migrations — fresh DB will break runtime):');
      violations.forEach((v) => console.log(`  ✗ ${v}`));
    }
    if (warnings.length) {
      if (warnings.length < 80 || VERBOSE) {
        console.log('\nWARNINGS:');
        warnings.forEach((w) => console.log(`  ⚠ ${w}`));
      } else {
        console.log(`\nWARNINGS: ${warnings.length} (suppressed — pass --verbose to see all)`);
      }
    }

    if (violations.length === 0) {
      console.log('\n✅ NO DRIFT — every TS-declared column/type/NOT NULL is satisfied by the checked-in migrations.');
      exitCode = 0;
    } else if (WARN_ONLY) {
      console.log('\n⚠ Drift detected, but --warn-only is set; exiting 0.');
      exitCode = 0;
    } else {
      console.log('\n✗ DRIFT DETECTED — see violations above.');
      console.log('  Fix by either adding the missing migrations under Jurexio-Platform-SDK/migrations/');
      console.log('  (additive ALTER TABLE … ADD COLUMN IF NOT EXISTS …) or by removing the column');
      console.log('  from the TS schema if it was declared in error.');
      exitCode = 1;
    }
  } catch (err) {
    console.error('[drift] ✗ infrastructure error:', err instanceof Error ? err.message : err);
    if (err instanceof Error && err.stack && VERBOSE) console.error(err.stack);
    exitCode = 2;
  } finally {
    if (pgHandle) stopPostgres(pgHandle);
  }
  process.exit(exitCode);
}

main();
