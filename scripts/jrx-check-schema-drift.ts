/**
 * jrx-check-schema-drift.ts — NV-SCHEMA-DRIFT-001 (CI guardrail)
 *
 * Catches the failure mode that produced tasks #263 and #265: the TS Drizzle
 * schema in `shared/**` and the checked-in SQL migrations
 * (`drizzle/000*.sql` + `Jurexio-Platform-SDK/migrations/*.sql`) silently
 * drift apart, and the divergence only surfaces when runtime writes fail
 * against a freshly-bootstrapped database.
 *
 * What it does
 *   1. Spins up an empty embedded Postgres in /tmp on a unique port (uses the
 *      Nix-provided initdb / pg_ctl so this runs in CI and on Replit).
 *   2. Applies every checked-in migration in lexical order:
 *        a. drizzle/*.sql           (auto-generated by drizzle-kit)
 *        b. migrations/*.sql        (hand-written catch-up files)
 *   3. Reflects the resulting DB and compares against the Drizzle schema
 *      exports listed in `drizzle.config.ts`.
 *   4. Fails (exit 1) when a column / type / NOT NULL / default declared in
 *      TS is missing from the migrations, OR when the migrations create
 *      columns that the TS schema does not know about for a TS-declared
 *      table (i.e. the migrations are ahead of the TS schema).
 *
 * Why this catches #263 + #265
 *   #263: shared/schema.ts declared workflow_id / organization_id / steps /
 *         triggers / jurisdiction / status / version / etc. on sdk_workflows
 *         that no migration ever created → runtime INSERTs failed in prod.
 *         This check would have failed CI: "MISSING COLUMN
 *         public.sdk_workflows.workflow_id".
 *   #265: had to hand-write 2026-05-13-sdk-workflows-schema-catchup.sql to
 *         bring fresh DBs in line. Re-running this check after the
 *         catch-up migration confirms parity is restored — i.e. the
 *         guardrail is the regression test for #265 itself.
 *
 * Exit codes
 *   0 — no drift
 *   1 — drift detected
 *   2 — infrastructure failure (Postgres failed to start, migration syntax
 *       error, etc.) — surfaced separately so a CI red is debuggable.
 *
 * Usage
 *   npm run guardrail:schema-drift          # fails on drift
 *   npm run guardrail:schema-drift -- --warn-only  # report only, exit 0
 *   JRX_DRIFT_KEEP_PG=1 npm run guardrail:schema-drift  # leave the temp
 *     Postgres + data dir running for manual inspection
 */

