#!/usr/bin/env bash
# JRX-INFRA-OPTION-B-001 — idempotent Option B stack: S3, VPC/SG, RDS Postgres 15, ElastiCache Redis, EC2.
# Never touches nysdev (i-0df71e5ea1df8f588) or NYV SSM paths. JRX SSM bootstrap is optional (/jurexio/prod/* only).
#
# Usage:
#   bash scripts/jrx-infra-apply-option-b.sh              # dry-run (default)
#   bash scripts/jrx-infra-apply-option-b.sh --dry-run
#   bash scripts/jrx-infra-apply-option-b.sh --apply      # creates/skips AWS resources
#
# Env: JRX_AWS_REGION, JRX_DEPLOY_BUCKET, JRX_VPC_ID, JRX_IAM_INSTANCE_PROFILE,
#      JRX_BOOTSTRAP_SSM=1 (with --apply only), JRX_RDS_ADMIN_URL (optional post-create pgvector + app role)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

NYSDEV_INSTANCE_ID="i-0df71e5ea1df8f588"
APPLY=0
REGION="${JRX_AWS_REGION:-ap-south-1}"
DEPLOY_BUCKET="${JRX_DEPLOY_BUCKET:-jurexio-deploy-artifacts}"
VPC_ID="${JRX_VPC_ID:-}"
IAM_PROFILE="${JRX_IAM_INSTANCE_PROFILE:-JRX_SSM_BEDROCK_INSTANCE_PROFILE_PLACEHOLDER}"

RDS_ID="${JRX_RDS_INSTANCE_ID:-jrx-enterprise-pg}"
RDS_CLASS="db.t4g.medium"
RDS_ENGINE="postgres"
RDS_ENGINE_VERSION="${JRX_RDS_ENGINE_VERSION:-15}"
RDS_MASTER_USER="${JRX_RDS_MASTER_USER:-jrxadmin}"
RDS_DB_NAME="${JRX_DB_NAME:-jurexio}"
RDS_STORAGE_GB="${JRX_RDS_ALLOCATED_STORAGE:-50}"

REDIS_CLUSTER_ID="${JRX_REDIS_CLUSTER_ID:-jrx-enterprise-redis}"
REDIS_NODE_TYPE="cache.t4g.micro"
REDIS_ENGINE_VERSION="${JRX_REDIS_ENGINE_VERSION:-7.1}"

EC2_NAME="${JRX_EC2_NAME_TAG:-jrx-enterprise-option-b}"
EC2_TYPE="t3.xlarge"
AL2023_SSM_PARAM="/aws/service/ami-amazon-linux-latest/al2023-ami-kernel-default-x86_64"

SG_RDS_NAME="jrx-option-b-rds"
SG_REDIS_NAME="jrx-option-b-redis"
SG_EC2_NAME="jrx-option-b-ec2"
DB_SUBNET_GROUP="${JRX_DB_SUBNET_GROUP:-jrx-option-b-db-subnets}"
CACHE_SUBNET_GROUP="${JRX_CACHE_SUBNET_GROUP:-jrx-option-b-cache-subnets}"

GENERATED_ENV="${JRX_GENERATED_ENV_FILE:-env.production.jurexio.generated}"

while [ $# -gt 0 ]; do
  case "$1" in
    --apply) APPLY=1; shift ;;
    --dry-run) APPLY=0; shift ;;
    -h|--help)
      sed -n '1,20p' "$0"
      exit 0
      ;;
    *)
      echo "unknown arg: $1 (use --dry-run or --apply)" >&2
      exit 2
      ;;
  esac
done

AWS_CLI=0
command -v aws >/dev/null 2>&1 && AWS_CLI=1
if [ "$AWS_CLI" != "1" ] && [ "$APPLY" = "1" ]; then
  echo "aws cli required for --apply" >&2
  exit 1
fi
if [ "$AWS_CLI" != "1" ]; then
  echo "warn: aws cli not installed — plan-only dry-run" >&2
fi

AWS_OK=0
if [ "$AWS_CLI" = "1" ] && aws sts get-caller-identity --region "$REGION" >/dev/null 2>&1; then
  AWS_OK=1
else
  echo "warn: AWS credentials unavailable — plan-only output (no describe/create calls)" >&2
fi

guardrail_reminder() {
  cat <<'EOF'
== JRX guardrails (Option B apply) ==
- Do NOT deploy to or modify nysdev i-0df71e5ea1df8f588.
- Do NOT write SSM under /nyv/* or /nyayavigya/*; use /jurexio/prod/* only.
- Do NOT log or commit secret values; review env.production.jurexio.generated (gitignored).
EOF
}

if [ "$APPLY" = "1" ]; then
  guardrail_reminder
  echo ""
fi

mode_label="dry-run"
[ "$APPLY" = "1" ] && mode_label="apply"

echo "== JRX Option B infra (${mode_label}) region=${REGION} =="
echo "   S3=${DEPLOY_BUCKET} RDS=${RDS_ID} Redis=${REDIS_CLUSTER_ID} EC2=${EC2_NAME}/${EC2_TYPE}"

# --- generated env (resource IDs only, no secrets) ---
GEN_EC2_ID=""
GEN_RDS_ENDPOINT=""
GEN_REDIS_ENDPOINT=""
GEN_VPC=""
GEN_SG_RDS=""
GEN_SG_REDIS=""
GEN_SG_EC2=""

write_generated_env() {
  local ts
  ts="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  cat >"$GENERATED_ENV" <<EOF
# Generated by scripts/jrx-infra-apply-option-b.sh at ${ts} — gitignored, no secret values.
JRX_AWS_REGION=${REGION}
JRX_DEPLOY_BUCKET=${DEPLOY_BUCKET}
JRX_VPC_ID=${GEN_VPC:-}
JRX_EC2_INSTANCE_ID=${GEN_EC2_ID:-}
JRX_RDS_INSTANCE_ID=${RDS_ID}
JRX_RDS_ENDPOINT=${GEN_RDS_ENDPOINT:-}
JRX_RDS_DB_NAME=${RDS_DB_NAME}
JRX_REDIS_CLUSTER_ID=${REDIS_CLUSTER_ID}
JRX_REDIS_ENDPOINT=${GEN_REDIS_ENDPOINT:-}
JRX_SG_EC2_ID=${GEN_SG_EC2:-}
JRX_SG_RDS_ID=${GEN_SG_RDS:-}
JRX_SG_REDIS_ID=${GEN_SG_REDIS:-}
JRX_IAM_INSTANCE_PROFILE=${IAM_PROFILE}
# Operator: copy non-empty lines into env.production.jurexio; set AWS keys locally.
EOF
  echo "wrote ${GENERATED_ENV} (IDs/endpoints only)"
}

resolve_vpc() {
  if [ -n "$VPC_ID" ]; then
    GEN_VPC="$VPC_ID"
    echo "vpc: using JRX_VPC_ID=${GEN_VPC}"
    return 0
  fi
  if [ "$AWS_OK" != "1" ]; then
    echo "vpc: would discover default VPC (set JRX_VPC_ID to override)"
    return 0
  fi
  GEN_VPC="$(aws ec2 describe-vpcs --region "$REGION" \
    --filters Name=isDefault,Values=true \
    --query 'Vpcs[0].VpcId' --output text)"
  if [ -z "$GEN_VPC" ] || [ "$GEN_VPC" = "None" ]; then
    echo "error: no default VPC; set JRX_VPC_ID" >&2
    exit 1
  fi
  VPC_ID="$GEN_VPC"
  echo "vpc: default ${GEN_VPC}"
}

subnet_ids_csv() {
  aws ec2 describe-subnets --region "$REGION" \
    --filters "Name=vpc-id,Values=${VPC_ID}" \
    --query 'Subnets[*].SubnetId' --output text | tr '\t' ','
}

ensure_s3_bucket() {
  if [ "$AWS_OK" = "1" ]; then
    if aws s3api head-bucket --bucket "$DEPLOY_BUCKET" 2>/dev/null; then
      echo "s3: skip exists s3://${DEPLOY_BUCKET}"
      return 0
    fi
  else
    echo "s3: would create bucket ${DEPLOY_BUCKET} (region=${REGION})"
    return 0
  fi
  if [ "$APPLY" != "1" ]; then
    echo "s3: would create bucket ${DEPLOY_BUCKET}"
    return 0
  fi
  if [ "$REGION" = "us-east-1" ]; then
    aws s3api create-bucket --bucket "$DEPLOY_BUCKET" --region "$REGION" >/dev/null
  else
    aws s3api create-bucket --bucket "$DEPLOY_BUCKET" --region "$REGION" \
      --create-bucket-configuration "LocationConstraint=${REGION}" >/dev/null
  fi
  echo "s3: created ${DEPLOY_BUCKET}"
}

find_or_create_sg() {
  local name="$1"
  local desc="$2"
  local out_var="$3"
  local existing=""
  local gid=""
  if [ "$AWS_OK" = "1" ] && [ -n "${VPC_ID:-}" ]; then
    existing="$(aws ec2 describe-security-groups --region "$REGION" \
      --filters "Name=group-name,Values=${name}" "Name=vpc-id,Values=${VPC_ID}" \
      --query 'SecurityGroups[0].GroupId' --output text 2>/dev/null || true)"
    if [ -n "$existing" ] && [ "$existing" != "None" ]; then
      echo "sg: skip exists ${name} ${existing}" >&2
      gid="$existing"
    fi
  fi
  if [ -z "$gid" ]; then
    if [ "$APPLY" != "1" ] || [ "$AWS_OK" != "1" ] || [ -z "${VPC_ID:-}" ]; then
      echo "sg: would create ${name} in vpc=${VPC_ID:-<unset>}" >&2
    else
      gid="$(aws ec2 create-security-group --region "$REGION" \
        --group-name "$name" --description "$desc" --vpc-id "$VPC_ID" \
        --query GroupId --output text)"
      echo "sg: created ${name} ${gid}" >&2
    fi
  fi
  printf -v "$out_var" '%s' "$gid"
}

authorize_sg_ingress() {
  local sg="$1"
  shift
  [ -z "$sg" ] && return 0
  if [ "$APPLY" != "1" ] || [ "$AWS_OK" != "1" ]; then
    echo "sg: would authorize ingress on ${sg} ($*)"
    return 0
  fi
  aws ec2 authorize-security-group-ingress --region "$REGION" \
    --group-id "$sg" "$@" 2>/dev/null || true
}

ensure_db_subnet_group() {
  if [ "$AWS_OK" = "1" ]; then
    if aws rds describe-db-subnet-groups --region "$REGION" \
      --db-subnet-group-name "$DB_SUBNET_GROUP" >/dev/null 2>&1; then
      echo "rds-subnet-group: skip exists ${DB_SUBNET_GROUP}"
      return 0
    fi
  fi
  local subs
  subs="$(subnet_ids_csv 2>/dev/null || true)"
  if [ "$APPLY" != "1" ] || [ "$AWS_OK" != "1" ] || [ -z "$subs" ]; then
    echo "rds-subnet-group: would create ${DB_SUBNET_GROUP} subnets=${subs:-<discover>}"
    return 0
  fi
  # shellcheck disable=SC2086
  aws rds create-db-subnet-group --region "$REGION" \
    --db-subnet-group-name "$DB_SUBNET_GROUP" \
    --db-subnet-group-description "JRX Option B RDS subnets" \
    --subnet-ids ${subs//,/ } >/dev/null
  echo "rds-subnet-group: created ${DB_SUBNET_GROUP}"
}

ensure_cache_subnet_group() {
  if [ "$AWS_OK" = "1" ]; then
    if aws elasticache describe-cache-subnet-groups --region "$REGION" \
      --cache-subnet-group-name "$CACHE_SUBNET_GROUP" >/dev/null 2>&1; then
      echo "cache-subnet-group: skip exists ${CACHE_SUBNET_GROUP}"
      return 0
    fi
  fi
  local subs
  subs="$(subnet_ids_csv 2>/dev/null || true)"
  if [ "$APPLY" != "1" ] || [ "$AWS_OK" != "1" ] || [ -z "$subs" ]; then
    echo "cache-subnet-group: would create ${CACHE_SUBNET_GROUP} subnets=${subs:-<discover>}"
    return 0
  fi
  # shellcheck disable=SC2086
  aws elasticache create-cache-subnet-group --region "$REGION" \
    --cache-subnet-group-name "$CACHE_SUBNET_GROUP" \
    --cache-subnet-group-description "JRX Option B Redis subnets" \
    --subnet-ids ${subs//,/ } >/dev/null
  echo "cache-subnet-group: created ${CACHE_SUBNET_GROUP}"
}

ensure_rds() {
  if [ "$AWS_OK" = "1" ]; then
    if aws rds describe-db-instances --region "$REGION" \
      --db-instance-identifier "$RDS_ID" >/dev/null 2>&1; then
      GEN_RDS_ENDPOINT="$(aws rds describe-db-instances --region "$REGION" \
        --db-instance-identifier "$RDS_ID" \
        --query 'DBInstances[0].Endpoint.Address' --output text)"
      echo "rds: skip exists ${RDS_ID} endpoint=${GEN_RDS_ENDPOINT}"
      return 0
    fi
  fi
  if [ "$APPLY" != "1" ] || [ "$AWS_OK" != "1" ]; then
    echo "rds: would create ${RDS_ID} ${RDS_ENGINE}${RDS_ENGINE_VERSION} ${RDS_CLASS} db=${RDS_DB_NAME}"
    return 0
  fi
  [ -n "$GEN_SG_RDS" ] || { echo "rds: missing RDS security group" >&2; exit 1; }
  aws rds create-db-instance --region "$REGION" \
    --db-instance-identifier "$RDS_ID" \
    --engine "$RDS_ENGINE" --engine-version "$RDS_ENGINE_VERSION" \
    --db-instance-class "$RDS_CLASS" \
    --master-username "$RDS_MASTER_USER" \
    --manage-master-user-password \
    --allocated-storage "$RDS_STORAGE_GB" --storage-type gp3 \
    --db-name "$RDS_DB_NAME" \
    --vpc-security-group-ids "$GEN_SG_RDS" \
    --db-subnet-group-name "$DB_SUBNET_GROUP" \
    --backup-retention-period 7 \
    --no-publicly-accessible \
    --tags "Key=Name,Value=${RDS_ID}" >/dev/null
  echo "rds: create started ${RDS_ID} (wait for available before pgvector step)"
  GEN_RDS_ENDPOINT="$(aws rds wait db-instance-available --region "$REGION" \
    --db-instance-identifier "$RDS_ID" 2>/dev/null; \
    aws rds describe-db-instances --region "$REGION" \
      --db-instance-identifier "$RDS_ID" \
      --query 'DBInstances[0].Endpoint.Address' --output text)"
  echo "rds: available endpoint=${GEN_RDS_ENDPOINT}"
}

ensure_redis() {
  if [ "$AWS_OK" = "1" ]; then
    if aws elasticache describe-cache-clusters --region "$REGION" \
      --cache-cluster-id "$REDIS_CLUSTER_ID" >/dev/null 2>&1; then
      GEN_REDIS_ENDPOINT="$(aws elasticache describe-cache-clusters --region "$REGION" \
        --cache-cluster-id "$REDIS_CLUSTER_ID" --show-cache-node-info \
        --query 'CacheClusters[0].CacheNodes[0].Endpoint.Address' --output text)"
      echo "redis: skip exists ${REDIS_CLUSTER_ID} endpoint=${GEN_REDIS_ENDPOINT}"
      return 0
    fi
  fi
  if [ "$APPLY" != "1" ] || [ "$AWS_OK" != "1" ]; then
    echo "redis: would create ${REDIS_CLUSTER_ID} ${REDIS_NODE_TYPE} engine=${REDIS_ENGINE_VERSION}"
    return 0
  fi
  [ -n "$GEN_SG_REDIS" ] || { echo "redis: missing Redis security group" >&2; exit 1; }
  aws elasticache create-cache-cluster --region "$REGION" \
    --cache-cluster-id "$REDIS_CLUSTER_ID" \
    --engine redis --engine-version "$REDIS_ENGINE_VERSION" \
    --cache-node-type "$REDIS_NODE_TYPE" \
    --num-cache-nodes 1 \
    --cache-subnet-group-name "$CACHE_SUBNET_GROUP" \
    --security-group-ids "$GEN_SG_REDIS" >/dev/null
  echo "redis: create started ${REDIS_CLUSTER_ID}"
  aws elasticache wait cache-cluster-available --region "$REGION" \
    --cache-cluster-id "$REDIS_CLUSTER_ID" >/dev/null 2>&1 || true
  GEN_REDIS_ENDPOINT="$(aws elasticache describe-cache-clusters --region "$REGION" \
    --cache-cluster-id "$REDIS_CLUSTER_ID" --show-cache-node-info \
    --query 'CacheClusters[0].CacheNodes[0].Endpoint.Address' --output text)"
  echo "redis: endpoint=${GEN_REDIS_ENDPOINT}"
}

ensure_ec2() {
  if [ "$AWS_OK" = "1" ]; then
    local existing
    existing="$(aws ec2 describe-instances --region "$REGION" \
      --filters "Name=tag:Name,Values=${EC2_NAME}" "Name=instance-state-name,Values=pending,running,stopping,stopped" \
      --query 'Reservations[0].Instances[0].InstanceId' --output text 2>/dev/null || true)"
    if [ -n "$existing" ] && [ "$existing" != "None" ]; then
      if [ "$existing" = "$NYSDEV_INSTANCE_ID" ]; then
        echo "error: refusing nysdev instance tag collision" >&2
        exit 3
      fi
      GEN_EC2_ID="$existing"
      echo "ec2: skip exists ${GEN_EC2_ID} name=${EC2_NAME}"
      return 0
    fi
  fi
  if [ "$APPLY" != "1" ] || [ "$AWS_OK" != "1" ]; then
    echo "ec2: would launch ${EC2_TYPE} AL2023 profile=${IAM_PROFILE} name=${EC2_NAME}"
    return 0
  fi
  if [[ "$IAM_PROFILE" == *"PLACEHOLDER"* ]]; then
    echo "ec2: skip create — set JRX_IAM_INSTANCE_PROFILE to SSM+Bedrock profile name" >&2
    return 0
  fi
  [ -n "$GEN_SG_EC2" ] || { echo "ec2: missing EC2 security group" >&2; exit 1; }
  local ami subs subnet
  ami="$(aws ssm get-parameters --region "$REGION" --names "$AL2023_SSM_PARAM" \
    --query 'Parameters[0].Value' --output text)"
  subs="$(aws ec2 describe-subnets --region "$REGION" \
    --filters "Name=vpc-id,Values=${VPC_ID}" \
    --query 'Subnets[0].SubnetId' --output text)"
  GEN_EC2_ID="$(aws ec2 run-instances --region "$REGION" \
    --image-id "$ami" \
    --instance-type "$EC2_TYPE" \
    --iam-instance-profile "Name=${IAM_PROFILE}" \
    --security-group-ids "$GEN_SG_EC2" \
    --subnet-id "$subs" \
    --metadata-options "HttpTokens=required" \
    --tag-specifications "ResourceType=instance,Tags=[{Key=Name,Value=${EC2_NAME}}]" \
    --query 'Instances[0].InstanceId' --output text)"
  if [ "$GEN_EC2_ID" = "$NYSDEV_INSTANCE_ID" ]; then
    echo "error: refusing nysdev instance id" >&2
    exit 3
  fi
  echo "ec2: launched ${GEN_EC2_ID}"
}

post_rds_pgvector_and_app_db() {
  echo "== RDS post-create (pgvector + app role pattern) =="
  echo "  1) Master password: Secrets Manager (ManageMasterUserPassword) — do not log."
  echo "  2) Build JRX_RDS_ADMIN_URL locally; store RDS admin URL in SSM /jurexio/prod/ only if needed."
  echo "  3) bash scripts/jrx-provision-rds-database.sh  # logical db=${RDS_DB_NAME} app user"
  echo "  4) psql <app-db-url> -c 'CREATE EXTENSION IF NOT EXISTS vector;'  # pgvector for RAG"
  if [ "$APPLY" != "1" ] || [ -z "${JRX_RDS_ADMIN_URL:-}" ]; then
    return 0
  fi
  if [[ "${JRX_RDS_ADMIN_URL}" == *"nyayavigya"* ]]; then
    echo "error: refusing admin URL referencing nyayavigya" >&2
    exit 4
  fi
  echo "  running jrx-provision-rds-database.sh (password length only at end)..."
  bash "$ROOT/scripts/jrx-provision-rds-database.sh"
  local app_url
  app_url="${JRX_RDS_ADMIN_URL/postgres/${RDS_DB_NAME}}"
  if command -v psql >/dev/null 2>&1; then
    psql "$app_url" -v ON_ERROR_STOP=1 -c "CREATE EXTENSION IF NOT EXISTS vector;" >/dev/null
    echo "  pgvector extension ensured on ${RDS_DB_NAME}"
  else
    echo "  warn: psql not installed — run CREATE EXTENSION vector manually"
  fi
}

bootstrap_ssm_if_requested() {
  if [ "$APPLY" != "1" ]; then
    if [ "${JRX_BOOTSTRAP_SSM:-0}" = "1" ]; then
      echo "ssm-bootstrap: would run jrx-ssm-bootstrap-bedrock-smoke.sh (set with --apply)"
    fi
    return 0
  fi
  if [ "${JRX_BOOTSTRAP_SSM:-0}" != "1" ]; then
    echo "ssm-bootstrap: skip (set JRX_BOOTSTRAP_SSM=1 to copy Bedrock params to /jurexio/prod/)"
    return 0
  fi
  : "${AWS_ACCESS_KEY_ID:?AWS_ACCESS_KEY_ID required for SSM bootstrap}"
  echo "ssm-bootstrap: invoking jrx-ssm-bootstrap-bedrock-smoke.sh (/jurexio/prod/ only)"
  bash "$ROOT/scripts/jrx-ssm-bootstrap-bedrock-smoke.sh"
}

# --- main flow ---
resolve_vpc
ensure_s3_bucket

find_or_create_sg "$SG_EC2_NAME" "JRX Option B EC2" GEN_SG_EC2
find_or_create_sg "$SG_RDS_NAME" "JRX Option B RDS" GEN_SG_RDS
find_or_create_sg "$SG_REDIS_NAME" "JRX Option B Redis" GEN_SG_REDIS

if [ -n "$GEN_SG_EC2" ] && [ -n "$GEN_SG_RDS" ]; then
  authorize_sg_ingress "$GEN_SG_RDS" --protocol tcp --port 5432 --source-group "$GEN_SG_EC2"
fi
if [ -n "$GEN_SG_EC2" ] && [ -n "$GEN_SG_REDIS" ]; then
  authorize_sg_ingress "$GEN_SG_REDIS" --protocol tcp --port 6379 --source-group "$GEN_SG_EC2"
fi
if [ -n "$GEN_SG_EC2" ]; then
  authorize_sg_ingress "$GEN_SG_EC2" --protocol tcp --port 22 --cidr 0.0.0.0/0
  authorize_sg_ingress "$GEN_SG_EC2" --protocol tcp --port 443 --cidr 0.0.0.0/0
  authorize_sg_ingress "$GEN_SG_EC2" --protocol tcp --port 5000 --cidr 0.0.0.0/0
fi

ensure_db_subnet_group
ensure_cache_subnet_group
ensure_rds
ensure_redis
ensure_ec2
post_rds_pgvector_and_app_db
write_generated_env
bootstrap_ssm_if_requested

echo "== Option B ${mode_label} complete =="
if [ "$APPLY" != "1" ]; then
  echo "(no resources mutated — re-run with --apply after operator GO)"
fi
