-- NV-CASE-API-P1-001 — extend cases view (append columns only — PG CREATE OR REPLACE rule)
CREATE OR REPLACE VIEW cases AS
 SELECT md5((court_level::text || '|'::text) || cnr::text) AS case_id,
    cnr,
    court_level,
    case_title,
    case_number,
    case_type,
    NULL::text AS case_type_full,
    md5((((((COALESCE(court_level, ''::character varying)::text || '|'::text) || COALESCE(court_code, ''::text)) || '|'::text) || COALESCE(court_establishment, ''::text)) || '|'::text) || COALESCE(court, ''::text)) AS establishment_id,
    petitioner,
    respondent,
    petitioner_advocate,
    respondent_advocate,
    filing_date,
    registration_date,
    first_hearing_date,
    next_hearing_date,
    decision_date,
    case_status,
    disposal_nature,
    current_judge,
    current_purpose,
    fir_no,
    fir_year,
    police_station,
    NULL::text AS police_district,
    citation,
    neutral_citation,
    extra,
    NULL::timestamp with time zone AS source_synced_at,
    diary_no,
    petitioner_address,
    respondent_address,
    petitioner_phone,
    respondent_phone,
    petitioner_email,
    respondent_email,
    petitioner_father_name,
    respondent_father_name,
    acts_json
   FROM cases_search_staging;
